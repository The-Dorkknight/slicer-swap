def _orca_version_string(inst: Install) -> str:
    nums = re.findall(r"\d+", inst.version or "")[:3]
    while len(nums) < 3:
        nums.append("0")
    return ".".join(nums) + ".0"


def orca_user(inst: Install) -> str:
    users = orca_user_dirs(inst)
    try:
        with open(os.path.join(inst.roots["data"], "OrcaSlicer.conf"), encoding="utf-8") as fh:
            pf = (json.load(fh).get("app") or {}).get("preset_folder")
        if pf and pf in users:
            return pf
    except (OSError, ValueError):
        pass
    return "default" if ("default" in users or not users) else users[0]


def install_orca_presets(inst: Install, native: Dict[str, Dict[str, Any]], name: str,
                         inherits: Optional[Dict[str, str]] = None, allow_running: bool = False) -> Result:
    _guard_running(inst, allow_running)
    res = Result()
    uid = orca_user(inst)
    base = os.path.join(inst.roots["data"], "user", uid)
    existing = set()
    for sub in ("process", "filament", "machine"):
        d = os.path.join(base, sub)
        if os.path.isdir(d):
            existing.update(f[:-5] for f in os.listdir(d) if f.endswith(".json"))
    final = _unique(existing, _safe_file_name(name))
    ver = _orca_version_string(inst)
    spec = (("printer", "machine", "printer_settings_id"), ("filament", "filament", "filament_settings_id"),
            ("print", "process", "print_settings_id"))
    for kind, sub, idkey in spec:
        vals = native.get(kind) or {}
        if not vals:
            continue
        doc: Dict[str, Any] = {"type": sub, "name": final, "from": "User", "instantiation": "true",
                               "inherits": (inherits or {}).get(kind, ""), "version": ver,
                               idkey: [final] if sub == "filament" else final}
        doc.update(dict(sorted(vals.items())))
        path = os.path.join(base, sub, final + ".json")
        _write_checked(path, json.dumps(doc, indent=4, ensure_ascii=False).encode("utf-8"), res)
        info = (f"sync_info = \nuser_id = {'' if uid == 'default' else uid}\nsetting_id = \nbase_id = \n"
                f"updated_time = {int(time.time())}\n")
        _write_checked(path[:-5] + ".info", info.encode("utf-8"), res)
    res.name, res.verified = final, True
    res.notes.append(f"Start OrcaSlicer and pick '{final}' as printer, filament and process (under 'User presets').")
    return res


