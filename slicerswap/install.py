def _unique(existing: set, name: str) -> str:
    if name not in existing:
        return name
    i = 2
    while f"{name} ({i})" in existing:
        i += 1
    return f"{name} ({i})"


def install_prusa_presets(inst: Install, native: Dict[str, Dict[str, Any]], name: str,
                          allow_running: bool = False) -> Result:
    """native = {"print": {...}, "filament": {...}, "printer": {...}} as produced by the converter."""
    from .slicer_fmt import _prusa_escape
    _guard_running(inst, allow_running)
    res = Result()
    data = inst.roots["data"]
    existing = set()
    for sub in ("print", "filament", "printer"):
        d = os.path.join(data, sub)
        if os.path.isdir(d):
            existing.update(f[:-4] for f in os.listdir(d) if f.endswith(".ini"))
    final = _unique(existing, _safe_file_name(name))
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d at %H:%M:%S UTC")
    for kind in ("printer", "filament", "print"):
        vals = dict(native.get(kind) or {})
        if not vals:
            continue
        # tie the print and filament presets to nothing: empty = usable with every printer
        lines = [f"# generated by SlicerSwap {__version__} on {stamp}"]
        lines += [f"{k} = {_prusa_escape(str(vals[k]))}" for k in sorted(vals)]
        _write_checked(os.path.join(data, kind, final + ".ini"), ("\n".join(lines) + "\n").encode("utf-8"), res)
    res.name, res.verified = final, True
    res.notes.append(f"Start PrusaSlicer and pick '{final}' in the Print settings, Filament and Printer drop-downs.")
    return res


