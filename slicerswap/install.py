class InstallError(Exception):
    pass


@dataclass
class Result:
    files: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    name: str = ""
    verified: bool = False


def _write_checked(path: str, data: bytes, res: Result, executable: bool = False):
    _atomic_write(path, data, executable)
    with open(path, "rb") as fh:
        if fh.read() != data:
            raise InstallError(f"File did not read back correctly: {path}")
    res.files.append(path)


def _safe_file_name(name: str) -> str:
    return re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip().rstrip(".") or "preset"


def _guard_running(inst: Install, allow_running: bool):
    if not allow_running and is_running(inst.slicer):
        raise InstallError(f"{SLICER_NAMES[inst.slicer]} is open. Close it first, then try again "
                           f"(it only reads these folders when it starts).")


