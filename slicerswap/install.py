"""Put new things into a slicer: converted presets, loose preset files, Cura plug-ins and scripts.

Rules kept throughout: never overwrite an existing preset (a new name is chosen instead),
write only inside the slicer's own data folders, and read every file back after writing.
How each slicer wants its files was checked by loading them in real Cura 5.13,
PrusaSlicer 2.7.2 and OrcaSlicer 2.4.2.
"""
