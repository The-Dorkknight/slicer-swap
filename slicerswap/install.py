def send_converted(paths: List[str], opts, inst: Install, cura_printer: Optional[str] = None,
                   allow_running: bool = False):
    """Convert profile file(s) and install the result straight into a slicer. Returns (Report, Result)."""
    from . import cura_fmt, slicer_fmt
    from .convert import LABEL, detect, read_canonical
    _guard_running(inst, allow_running)
    res = None
    src_guess = opts.source or detect(paths)
    machine = None
    if inst.slicer == "cura":
        machines = cura_machines(inst)
        if not machines:
            raise InstallError("This Cura has no printer set up yet. Add your printer in Cura first.")
        machine = next((m for m in machines if m["name"] == cura_printer or m["id"] == cura_printer), None)
        if machine is None and cura_printer:        # part of the name is enough when it fits exactly one printer
            part = [m for m in machines if cura_printer.lower() in m["name"].lower()]
            machine = part[0] if len(part) == 1 else None
        if machine is None:
            if cura_printer or len(machines) > 1:
                raise InstallError("Choose which Cura printer the profile is for: " + ", ".join(m["name"] for m in machines))
            machine = machines[0]
    native_ext = {"orca": (".json",), "prusa": (".ini",), "cura": (".curaprofile", ".inst.cfg")}[inst.slicer]
    if src_guess == inst.slicer and all(p.lower().endswith(native_ext) for p in paths) and not opts.overrides:
        # same slicer: nothing to convert, install the files as they are (no setting is lost)
        from .mapping import Report
        result = install_native_files(inst, paths, cura_printer=machine["name"] if machine else None, allow_running=True)
        rep = Report(source=LABEL[src_guess], target=LABEL[inst.slicer] + " (installed)")
        rep.note(f"These files already are {LABEL[inst.slicer]} presets: installed as they are, nothing was converted.")
        for n in result.notes:
            rep.note(n)
        rep.files = list(result.files)
        return rep, result
    if src_guess == "cura" or inst.slicer == "cura":
        res = ce.Resources(opts.cura_resources)
    src, C, rep = read_canonical(paths, opts, res)
    rep.target = LABEL[inst.slicer] + " (installed)"
    name = opts.name or f"{C.get('name', 'Imported')} ({LABEL[src]})"
    if inst.slicer == "cura":
        mdef = machine["definition"] if res._find_def(machine["definition"]) else "fdmprinter"
        if mdef != machine["definition"]:
            rep.note(f"Cura printer type '{machine['definition']}' is not known to SlicerSwap; treated as a generic printer.")
        vals, qt = cura_fmt.build_values(C, res, mdef, rep, src, material=machine.get("material"),
                                         variant=machine.get("variant"))
        result = install_cura_profile(inst, vals, name, machine, res, qt, allow_running=True)
        rep.note("Cura keeps bed size, start G-code and other machine settings per printer; they were not changed.")
    else:
        native = slicer_fmt.from_canon(inst.slicer, C, rep, src, target_version=inst.version or None)
        if inst.slicer == "prusa":
            result = install_prusa_presets(inst, native, name, allow_running=True)
        else:
            result = install_orca_presets(inst, native, name, opts.inherits, allow_running=True)
    rep.files = list(result.files)
    for n in result.notes:
        rep.note(n)
    return rep, result


