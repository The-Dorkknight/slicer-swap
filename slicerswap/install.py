def install_native_files(inst: Install, paths: List[str], cura_printer: Optional[str] = None,
                         allow_running: bool = False) -> Result:
    """Copy preset files that already are in this slicer's own format into place, under a free name."""
    _guard_running(inst, allow_running)
    res = Result()
    data = inst.roots["data"]
    if inst.slicer == "orca":
        uid = orca_user(inst)
        for p in paths:
            with open(p, encoding="utf-8") as fh:
                j = json.load(fh)
            sub = {"process": "process", "filament": "filament", "machine": "machine"}.get(j.get("type"))
            if not sub:
                raise InstallError(f"{os.path.basename(p)} does not say whether it is a process, filament or machine preset.")
            d = os.path.join(data, "user", uid, sub)
            existing = {f[:-5] for f in os.listdir(d)} if os.path.isdir(d) else set()
            final = _unique(existing, _safe_file_name(j.get("name") or os.path.splitext(os.path.basename(p))[0]))
            j["name"] = final
            j["from"] = "User"
            j.setdefault("version", _orca_version_string(inst))
            _write_checked(os.path.join(d, final + ".json"), json.dumps(j, indent=4, ensure_ascii=False).encode("utf-8"), res)
            info = f"sync_info = \nuser_id = {'' if uid == 'default' else uid}\nsetting_id = \nbase_id = \nupdated_time = {int(time.time())}\n"
            _write_checked(os.path.join(d, final + ".info"), info.encode("utf-8"), res)
            res.notes.append(f"Added {sub} preset '{final}'.")
    elif inst.slicer == "prusa":
        from .slicer_fmt import _parse_ini_lines, _prusa_escape
        from .gcode import native_types
        types = native_types("prusa")
        for p in paths:
            with open(p, encoding="utf-8", errors="replace") as fh:
                triples = _parse_ini_lines(fh.read())
            sections: Dict[Tuple[str, str], Dict[str, str]] = {}
            base = os.path.splitext(os.path.basename(p))[0]
            for sec, k, v in triples:
                if sec and ":" in sec:                       # config bundle: [print:Name]
                    kind, nm = sec.split(":", 1)
                    if kind in ("print", "filament", "printer") and not nm.startswith("*"):
                        sections.setdefault((kind, nm), {})[k] = v
                elif sec is None:                            # exported config: split by option type
                    kind = types.get(k, {}).get("sec")
                    if kind:
                        sections.setdefault((kind, base), {})[k] = v
            if not sections:
                raise InstallError(f"{os.path.basename(p)}: no PrusaSlicer presets found in this file.")
            for (kind, nm), vals in sections.items():
                d = os.path.join(data, kind)
                existing = {f[:-4] for f in os.listdir(d)} if os.path.isdir(d) else set()
                final = _unique(existing, _safe_file_name(nm))
                text = f"# installed by SlicerSwap {__version__}\n" + "".join(
                    f"{k} = {_prusa_escape(vals[k])}\n" for k in sorted(vals))
                _write_checked(os.path.join(d, final + ".ini"), text.encode("utf-8"), res)
                res.notes.append(f"Added {kind} preset '{final}'.")
    else:
        machines = cura_machines(inst)
        machine = next((m for m in machines if m["name"] == cura_printer or m["id"] == cura_printer), None) or \
            (machines[0] if len(machines) == 1 else None)
        if machine is None:
            raise InstallError("Choose which Cura printer the profile is for.")
        r = ce.Resources()
        for p in paths:
            prof = ce.read_cura_file(p)
            vals = dict(prof.global_changes)
            vals.update(prof.extruder_changes)
            mdef = machine["definition"] if r._find_def(machine["definition"]) else "fdmprinter"
            qt = prof.quality_type if prof.quality_type in r.quality_types(mdef) else \
                ce.choose_quality(r, mdef, float(vals.get("layer_height") or 0.2))[0]
            if qt != prof.quality_type:
                res.notes.append(f"'{prof.name}': quality type '{prof.quality_type}' does not exist for this printer; using '{qt}'.")
            one = install_cura_profile(inst, vals, prof.name, machine, r, qt, allow_running=True)
            res.files += one.files
            res.notes += one.notes
    res.verified = True
    return res


