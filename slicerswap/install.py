def cura_setting_version(inst: Install) -> int:
    for sub in ("machine_instances", "extruders", "quality_changes"):
        d = os.path.join(inst.roots["data"], sub)
        if os.path.isdir(d):
            for fn in os.listdir(d):
                sv = _read_cfg(os.path.join(d, fn)).get("metadata", {}).get("setting_version")
                if sv and sv.isdigit():
                    return int(sv)
    sv = _read_cfg(os.path.join(inst.roots["config"], "cura.cfg")).get("metadata", {}).get("setting_version")
    return int(sv) if sv and sv.isdigit() else ce.setting_version()


def install_cura_profile(inst: Install, values: Dict[str, Any], name: str, machine: Dict[str, Any],
                         res_data: ce.Resources, quality_type: str, allow_running: bool = False) -> Result:
    """Write a custom profile for one of this Cura's printers (machine = an entry of cura_machines())."""
    _guard_running(inst, allow_running)
    out = Result()
    data = inst.roots["data"]
    qdir = os.path.join(data, "quality_changes")
    names = set()
    if os.path.isdir(qdir):
        for fn in os.listdir(qdir):
            names.add(_read_cfg(os.path.join(qdir, fn)).get("general", {}).get("name", ""))
    final = name if name not in names else next(f"{name} #{i}" for i in range(2, 1000) if f"{name} #{i}" not in names)
    mdef = machine["definition"]
    qdef = res_data.quality_definition(mdef) if res_data._find_def(mdef) else mdef
    defs = res_data.setting_definitions(mdef) if res_data._find_def(mdef) else res_data.setting_definitions("fdmprinter")
    sv = cura_setting_version(inst)
    exdef = (machine.get("extruder_definitions") or ["fdmextruder"])[0]
    glob_vals = {k: v for k, v in values.items() if str(defs.get(k, {}).get("settable_per_extruder", True)).lower() == "false"}
    ex_vals = {k: v for k, v in values.items() if k not in glob_vals}

    def cid(prefix: str) -> str:
        base = (prefix + "_" + final).lower().replace(" ", "_")
        cand, i = base, 2
        while os.path.exists(os.path.join(qdir, quote_plus(cand) + ".inst.cfg")):
            cand, i = f"{base}_{i}", i + 1
        return cand
    containers = [
        (cid(mdef), {"type": "quality_changes", "quality_type": quality_type, "setting_version": str(sv),
                     "intent_category": "default"}, glob_vals),
        (cid(exdef), {"setting_version": str(sv), "type": "quality_changes", "quality_type": quality_type,
                      "position": "0"}, ex_vals),
    ]
    for container_id, meta, vals in containers:
        ic = ce.InstCfg(general={"version": "4", "name": final, "definition": qdef}, metadata=meta,
                        values={k: ce.format_cura_value(vals[k]) for k in sorted(vals)})
        _write_checked(os.path.join(qdir, quote_plus(container_id) + ".inst.cfg"),
                       ce.write_inst_cfg(ic).encode("utf-8"), out)
    out.name, out.verified = final, True
    out.notes.append(f"Start Cura, select printer '{machine['name']}', then choose '{final}' under Custom profiles.")
    return out


