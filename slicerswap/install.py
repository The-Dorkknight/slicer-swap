def _plugin_root_in_zip(names: List[str]) -> Optional[str]:
    """Folder inside a zip that directly holds plugin.json and __init__.py ('' = top level)."""
    cands = [n[: -len("plugin.json")] for n in names if n.endswith("plugin.json")]
    cands = [c for c in cands if (c + "__init__.py") in names]
    return min(cands, key=len) if cands else None


SAFE_ID = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}$")


def plugin_id_from_name(name: str) -> str:
    """The id for a plug-in that arrives as a folder or zip: the same whichever way it comes, so a GitHub
    download (Name-main, Name-v1.2) and the plain folder do not end up installed twice."""
    pid = re.sub(r"[-_ ]?(main|master|v?\d+(\.\d+)*)$", "", name) or name
    return re.sub(r"[^A-Za-z0-9_]", "", pid) or "Plugin"


def _json_from(data: bytes, what: str) -> Dict[str, Any]:
    try:
        d = json.loads(data.decode("utf-8-sig"))
    except (ValueError, RecursionError):
        raise InstallError(f"The plug-in's {what} is damaged (not readable JSON). Nothing was installed.") from None
    if not isinstance(d, dict):
        raise InstallError(f"The plug-in's {what} is not in the form Cura expects. Nothing was installed.")
    return d


def read_plugin_source(path: str) -> Dict[str, Any]:
    """Describe a plug-in the user picked: a .curapackage, a zip of the plug-in folder, or the folder itself."""
    try:
        info = _read_plugin_source(path)
    except (zipfile.BadZipFile, zipfile.LargeZipFile, OSError, EOFError, KeyError) as exc:
        raise InstallError(f"Could not read that plug-in file ({exc.__class__.__name__}: {str(exc)[:120]}). "
                           f"Nothing was installed.") from None
    pid = info.get("plugin_id")
    if not isinstance(pid, str) or not SAFE_ID.match(pid) or ".." in pid:
        raise InstallError(f"The plug-in's id {pid!r} is not a valid Cura package id. Nothing was installed.")
    return info


def _read_plugin_source(path: str) -> Dict[str, Any]:
    info: Dict[str, Any] = {"path": path, "kind": None}
    if os.path.isdir(path):
        pj = os.path.join(path, "plugin.json")
        if not (os.path.isfile(pj) and os.path.isfile(os.path.join(path, "__init__.py"))):
            raise InstallError("That folder is not a Cura plug-in (plugin.json and __init__.py must be directly inside).")
        with open(pj, "rb") as fh:
            meta = _json_from(fh.read(), "plugin.json")
        folder = os.path.basename(os.path.abspath(path))
        info.update(kind="folder", plugin_id=plugin_id_from_name(folder), meta=meta,
                    faults=plugcheck.faults_in_dir(path))
    elif zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as zf:
            names = zf.namelist()
            pkg = next((n for n in names if n == "package.json"), None)
            if pkg and any(n.startswith("files/plugins/") for n in names):
                pi = _json_from(zf.read(pkg), "package.json")
                if pi.get("package_type", "plugin") != "plugin":
                    raise InstallError(f"This package is a '{pi.get('package_type')}' package, not a plug-in.")
                info.update(kind="curapackage", plugin_id=pi.get("package_id"), package_info=pi,
                            meta={"name": pi.get("display_name"), "version": pi.get("package_version"),
                                  "author": (pi.get("author") or {}).get("display_name")},
                            faults=plugcheck.faults_in_zip(zf, "files/plugins/"))
            else:
                root = _plugin_root_in_zip(names)
                if root is None:
                    raise InstallError("No Cura plug-in found in that zip (it needs plugin.json and __init__.py).")
                meta = _json_from(zf.read(root + "plugin.json"), "plugin.json")
                pid = root.rstrip("/").split("/")[-1] if root else os.path.splitext(os.path.basename(path))[0]
                info.update(kind="zip", plugin_id=plugin_id_from_name(pid), meta=meta, zip_root=root,
                            faults=plugcheck.faults_in_zip(zf, root))
    elif path.lower().endswith((".zip", ".curapackage")):
        raise InstallError("That file is damaged or incomplete (it is not a readable zip). Download it again.")
    else:
        raise InstallError("Pick a .curapackage file, a zip of a plug-in, or the plug-in's folder.")
    if not info.get("plugin_id"):
        raise InstallError("Could not work out the plug-in's id.")
    return info


def _sdk_semver(meta: Dict[str, Any]) -> str:
    v = meta.get("supported_sdk_versions")
    if isinstance(v, list) and v:
        return str(sorted(v, key=lambda s: [int(x) for x in re.findall(r"\d+", s)])[0])
    api = meta.get("api")
    return f"{api}.0.0" if api else "8.0.0"


def build_curapackage(info: Dict[str, Any], out_path: str) -> Dict[str, Any]:
    """Wrap a plug-in folder/zip as a .curapackage so Cura's own package manager installs and lists it."""
    meta, pid = info["meta"], info["plugin_id"]
    package_info = {
        "package_id": pid, "package_type": "plugin", "display_name": meta.get("name") or pid,
        "description": meta.get("description") or "", "package_version": str(meta.get("version") or "0.0.0"),
        "sdk_version": int(str(_sdk_semver(meta)).split(".")[0]), "sdk_version_semver": _sdk_semver(meta),
        "website": meta.get("website") or "", "author": {"author_id": re.sub(r"\W", "", str(meta.get("author") or "unknown")) or "unknown",
                                                           "display_name": str(meta.get("author") or "unknown"),
                                                           "email": "", "website": ""},
        "tags": ["plugin"],
    }
    with zipfile.ZipFile(out_path, "w", compression=zipfile.ZIP_DEFLATED) as out:
        out.writestr("package.json", json.dumps(package_info, indent=4))
        out.writestr("[Content_Types].xml", '<?xml version="1.0" encoding="UTF-8"?>\n<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                                            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                                            '<Default Extension="json" ContentType="application/x-ultimaker-package-info+json"/></Types>')
        prefix = f"files/plugins/{pid}/"
        if info["kind"] == "folder":
            base = info["path"]
            for dp, dns, fns in os.walk(base):
                dns[:] = [d for d in dns if d not in ("__pycache__", ".git", ".github")]
                for fn in fns:
                    if fn.endswith((".pyc", ".pyo")):
                        continue
                    full = os.path.join(dp, fn)
                    out.write(full, prefix + os.path.relpath(full, base).replace(os.sep, "/"))
        else:
            root = info["zip_root"]
            with zipfile.ZipFile(info["path"]) as src:
                for n in src.namelist():
                    if not n.startswith(root) or n.endswith("/") or "__pycache__" in n or "/.git/" in n:
                        continue
                    rel = n[len(root):]
                    if rel.startswith("/") or ".." in rel.split("/"):
                        continue
                    out.writestr(prefix + rel, src.read(n))
    return package_info


def _packages_for_write(inst: Install) -> Tuple[str, Dict[str, Any]]:
    """Cura's package list, or InstallError (with nothing changed) when it exists but cannot be read."""
    try:
        return cura_packages(inst, strict=True)
    except PackagesDamaged as e:
        raise InstallError("Nothing was changed. " + damaged_text(e)) from None


def _write_packages(pk_path: str, pk: Dict[str, Any], res: Result):
    """Write Cura's package list, keeping the version before as packages.json.bak (only ever a readable one)."""
    if os.path.isfile(pk_path) and os.path.getsize(pk_path) > 0:
        shutil.copy2(pk_path, pk_path + ".bak")
    _write_checked(pk_path, json.dumps(pk, indent=4).encode("utf-8"), res)


def install_cura_plugin(inst: Install, source: str, allow_running: bool = False, allow_faulty: bool = False) -> Result:
    """Hand a plug-in to Cura's own package manager: it installs it the next time Cura starts.
    A plug-in with the icon fault that stops Cura starting is refused (allow_faulty is for tests)."""
    if inst.slicer != "cura":
        raise InstallError("Only Cura has installable plug-ins. PrusaSlicer and OrcaSlicer do not.")
    _guard_running(inst, allow_running)
    info = read_plugin_source(source)
    res = Result(name=info["plugin_id"])
    pid = info["plugin_id"]
    faults = info.get("faults") or []
    shown = (info.get("meta") or {}).get("name") or pid
    if plugcheck.stops_cura(faults) and not allow_faulty:
        raise InstallError("Not installed. " + plugcheck.explain(shown, faults))
    if faults:
        res.notes.append("Warning: " + plugcheck.explain(shown, faults))
    pk_path, pk = _packages_for_write(inst)  # before anything is written
    cache_dir = os.path.join(inst.roots["cache"], "cura_packages")
    target = os.path.join(cache_dir, pid + ".curapackage")
    if info["kind"] == "curapackage":
        with open(source, "rb") as fh:
            data = fh.read()
        package_info = info["package_info"]
    else:
        with tempfile.TemporaryDirectory() as tmp:
            tmp_pkg = os.path.join(tmp, pid + ".curapackage")
            package_info = build_curapackage(info, tmp_pkg)
            with open(tmp_pkg, "rb") as fh:
                data = fh.read()
    _write_checked(target, data, res)
    package_info = dict(package_info, is_active=True, is_bundled=False, is_installed=False)
    pk.setdefault("installed", {})
    pk.setdefault("to_remove", [])
    pk.setdefault("to_install", {})
    pk.setdefault("dismissed", [])
    pk["to_install"][pid] = {"package_info": package_info, "filename": target}
    pk["to_remove"] = [x for x in pk["to_remove"] if x != pid]
    _write_packages(pk_path, pk, res)
    # a loose copy of the same plug-in would be loaded as well and clash
    loose = os.path.join(inst.roots["data"], "plugins", pid, "plugin.json")
    if os.path.isfile(loose):
        res.notes.append(f"A hand-copied folder plugins/{pid} already exists; Cura replaces it with the packaged version on start.")
    res.verified = True
    res.notes.append(f"'{package_info.get('display_name', pid)}' {package_info.get('package_version', '')} is queued. "
                     f"Start Cura: it installs the plug-in on start-up. Then press Check here.")
    return res


WHERE_HINT = ("If you cannot see it in Cura: tool-bar buttons only appear once a model is loaded. "
              "It is also listed under Marketplace > Manage packages (the cog), and some plug-ins add an Extensions menu.")


def _stamp(t: Optional[str]) -> Optional[datetime.datetime]:
    try:
        return datetime.datetime.strptime(t, "%Y-%m-%d %H:%M:%S") if t else None
    except ValueError:
        return None


def check_cura_plugin(inst: Install, plugin_id: str, plugin_name: Optional[str] = None,
                      session: Optional[plugcheck.Session] = None, running: Optional[bool] = None) -> Tuple[str, str]:
    """(state, explanation) from the plug-in's own files, Cura's package list, Cura's log and Cura's crash record.

    state: loaded   Cura loaded it and finished starting
           failed   it stops Cura starting, is switched off, or Cura reported an error
           unsure   Cura logged it as loaded but that start never finished (a crash looks like this)
           waiting  Cura has to be (re)started first
           missing  not installed
    """
    _p, pk = cura_packages(inst)
    pk = pk if isinstance(pk, dict) else {}
    if plugin_id in pk.get("to_install", {}):
        return "waiting", "Queued. Cura installs it the next time it starts."
    plugins = cura_plugins(inst)
    p = next((x for x in plugins if x["plugin_id"] == plugin_id), None) or \
        next((x for x in plugins if x["folder"] == plugin_id), None)
    if not p:
        return "missing", "Not installed in this Cura."
    pid = p["plugin_id"]
    # 1. a fault we can see in the files: do not wait for Cura to fall over
    faults = plugcheck.faults_in_dir(p["path"]) if p.get("path") else []
    if plugcheck.stops_cura(faults):
        return "failed", ("STOPS CURA FROM STARTING: " + plugcheck.reason(faults) +
                          " Select it and press 'Remove selected', then start Cura. It needs a fixed version from its author.")
    # 2. switched off inside Cura
    if pid in plugcheck.disabled_plugins(inst.roots["config"], inst.roots["data"]):
        return "failed", ("Switched off inside Cura. In Cura open Marketplace > Manage packages (the cog), "
                          "switch it on and restart Cura.")
    # 3. Cura's log of its last start
    s = session if session is not None else plugcheck.read_session(cura_log_path(inst))
    if s is None or not s.start:
        return "waiting", "Installed, but Cura has not been started since (no log yet). Start Cura, then press Check."
    try:
        installed_at = datetime.datetime.fromtimestamp(os.path.getmtime(os.path.join(p["path"], "plugin.json")))
    except (OSError, TypeError):
        installed_at = None
    last = _stamp(s.last)
    ev = s.events.get(pid)
    if ev is None:
        if installed_at and last and installed_at.replace(microsecond=0) > last:
            return "waiting", "Installed. Cura has not been started since. Start Cura, then press Check."
        return "failed", (f"Cura's last start ({s.start}) did not load this plug-in and gave no reason. "
                          f"Look in Cura's log for '{pid}'.")
    kind, when, detail = ev
    if kind == "disabled":
        return "failed", ("Switched off inside Cura. In Cura open Marketplace > Manage packages (the cog), "
                          "switch it on and restart Cura.")
    if kind == "incompatible":
        return "failed", f"Cura refused it at {when}: it was made for a different Cura version. Cura says: {detail}"
    if kind == "error":
        return "failed", f"Cura reported an error loading it at {when}: {detail}"
    have = str(p.get("version") or "")
    if detail and have and detail.split("-")[0] != have.split("-")[0]:
        return "waiting", f"Version {have} is installed, but Cura's last start loaded {detail}. Restart Cura, then press Check."
    listed = "in Cura's package list" if p.get("package") else "from its folder (not in Cura's package list)"
    if s.finished_after(when):
        text = f"Loaded by Cura at {when}, {listed}."
        if faults:
            text += " Warning: " + plugcheck.explain(p["name"], faults)
        return "loaded", text
    # Cura wrote "Loaded plugin" but never said its start-up was complete
    if running is None:
        running = is_running("cura")
    if running and not s.closed:
        return "waiting", f"Cura is still starting (it loaded the plug-in at {when}). Press Check again in a moment."
    crash = plugcheck.crash_note(inst.roots["data"], s.start)
    if crash:
        return "unsure", (f"NOT CONFIRMED. Cura loaded it at {when}, then crashed before its window was ready "
                          f"(Cura's crash record: {crash}). A plug-in can cause this. If Cura will not start, "
                          f"remove the plug-in you installed last and start Cura again.")
    return "unsure", (f"NOT CONFIRMED. Cura loaded it at {when}, but that start never finished "
                      f"(Cura was closed or stopped while starting). Start Cura again, then press Check.")


def cura_plugin_report(inst: Install) -> List[Tuple[Dict[str, Any], str, str]]:
    """[(plug-in, state, explanation)] for every user plug-in of this Cura, reading Cura's log once."""
    session = plugcheck.read_session(cura_log_path(inst))
    running = is_running("cura")
    out = []
    for p in cura_plugins(inst):
        if p["state"].startswith("will be removed"):
            out.append((p, "waiting", "Cura removes it the next time it starts."))
        else:
            st, why = check_cura_plugin(inst, p["folder"] or p["plugin_id"], session=session, running=running)
            out.append((p, st, why))
    return out


def remove_cura_plugin(inst: Install, folder: str, allow_running: bool = False) -> Result:
    """Ask Cura to uninstall a packaged plug-in on its next start; move a hand-copied folder aside."""
    _guard_running(inst, allow_running)
    if not isinstance(folder, str) or not SAFE_ID.match(folder) or ".." in folder:
        raise InstallError("That plug-in is not installed here.")
    res = Result(name=folder)
    try:
        pk_path, pk = cura_packages(inst, strict=True)
        damaged = None
    except PackagesDamaged as e:
        pk_path, pk, damaged = e.path, {}, e
    if folder in pk.get("to_install", {}):
        pk["to_install"].pop(folder)
        _write_packages(pk_path, pk, res)
        res.notes.append("Removed from the install queue.")
    elif folder in pk.get("installed", {}):
        pk.setdefault("to_remove", [])
        if folder not in pk["to_remove"]:
            pk["to_remove"].append(folder)
        _write_packages(pk_path, pk, res)
        res.notes.append("Cura will uninstall it the next time it starts (the same as Uninstall in Cura's Marketplace).")
    else:
        src = os.path.join(inst.roots["data"], "plugins", folder)
        if not os.path.isdir(src):
            raise InstallError("That plug-in is not installed here.")
        dst_base = os.path.join(inst.roots["data"], "plugins-removed-by-slicerswap")
        os.makedirs(dst_base, exist_ok=True)
        dst = os.path.join(dst_base, f"{folder}-{datetime.datetime.now().strftime('%Y%m%d-%H%M%S')}")
        shutil.move(src, dst)
        res.files.append(dst)
        res.notes.append(f"Moved out of Cura's plug-in folder (not deleted): {dst}")
        if damaged is not None:
            res.notes.append("Cura's package list was left as it is. " + damaged_text(damaged))
    res.verified = True
    return res


def install_cura_script(inst: Install, py_path: str, allow_running: bool = True) -> Result:
    """Copy a post-processing script into Cura's scripts folder (Extensions > Post Processing > Modify G-Code)."""
    if inst.slicer != "cura":
        raise InstallError("Post-processing script folders exist only in Cura.")
    if not py_path.lower().endswith(".py"):
        raise InstallError("A Cura post-processing script is a .py file.")
    res = Result(name=os.path.basename(py_path))
    with open(py_path, "rb") as fh:
        data = fh.read()
    if b"Script" not in data:
        res.notes.append("This file does not look like a Cura post-processing script (no 'Script' class); copied anyway.")
    dst = os.path.join(inst.roots["config"], "scripts", os.path.basename(py_path))
    if os.path.isfile(dst):
        with open(dst, "rb") as fh:
            if fh.read() == data:
                res.notes.append("Already installed (identical file).")
                res.verified = True
                return res
        keep = dst + "." + datetime.datetime.now().strftime("%Y%m%d-%H%M%S") + ".old"
        shutil.copy2(dst, keep)
        res.notes.append(f"The previous version was kept as {os.path.basename(keep)}.")
    _write_checked(dst, data, res)
    res.verified = True
    res.notes.append("Restart Cura; the script appears under Extensions > Post Processing > Modify G-Code > Add a script.")
    return res
